def _count_hits(keywords, desc_lower, min_len=1):
    return sum(1 for kw in keywords if len(kw) >= min_len and kw.lower() in desc_lower)

def is_description_aligned(category, description):
    """嚴謹版語意對齊檢查：舉證責任倒置——只有『明確屬於其他基礎分類』才判錯，否則保留。

    回傳 (bool, reason)。
    保留理由: other / catname / own_kw / uncovered / ambiguous
    刪除理由: other_kw:<分類>
    """
    desc_lower = description.lower()
    if category == "其他":
        return True, "other"
    if category.lower() in desc_lower:
        return True, "catname"
    kw_map = {**CATEGORY_KEYWORDS, **EXTRA_CATEGORY_KEYWORDS}
    own_kw = kw_map.get(category, [])
    if _count_hits(own_kw, desc_lower) >= 1:
        return True, "own_kw"
    if not own_kw:
        # 類別完全沒有關鍵字覆蓋 → 無法判斷，寧可保留
        return True, "uncovered"
    # 自己類別關鍵字完全沒命中 → 可疑。此時僅以「基礎分類」的關鍵字當作刪除證據，
    # 且只採長度 >= 2 的關鍵字（避免「還/車/水/早」等單字誤傷）。
    for c, kws in CATEGORY_KEYWORDS.items():
        if c == category or c == "其他":
            continue
        if _count_hits(kws, desc_lower, min_len=2) >= 1:
            return False, f"other_kw:{c}"
    return True, "ambiguous"

def filter_file(src_path, dst_path):
    total = 0
    kept = 0
    removed = []
    reason_stats = {}
    uncovered_cats = set()
    with open(src_path, "r", encoding="utf-8") as f:
        samples = [json.loads(l) for l in f if l.strip()]
    total = len(samples)
    kept_samples = []
    for s in samples:
        msgs = s.get("messages", [])
        ass = next((m["content"] for m in msgs if m["role"] == "assistant"), "")
        tc = re.search(r"<tool_call>(.*?)</tool_call>", ass)
        if tc:
            obj = json.loads(tc.group(1))
            args = obj.get("args", obj)
            cat = args.get("category", "")
            desc = args.get("description", "")
            ok, reason = is_description_aligned(cat, desc)
            reason_stats[reason] = reason_stats.get(reason, 0) + 1
            if ok:
                kept_samples.append(s)
                kept += 1
            else:
                removed.append((cat, desc[:40], reason))
    with open(dst_path, "w", encoding="utf-8") as f:
        for s in kept_samples:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")
    print(f"Total: {total}, Kept: {kept}, Removed: {total - kept}")
    print(f"原因統計: {reason_stats}")
    print(f"Removed samples (first 15):")
    for cat, desc, reason in removed[:15]:
        print(f"  [{cat}] {desc}  <- {reason}")
    rem_path = dst_path + ".removed.jsonl"
    with open(rem_path, "w", encoding="utf-8") as f:
        for s in samples:
            msgs = s.get("messages", [])
            ass = next((m["content"] for m in msgs if m["role"] == "assistant"), "")
            tc = re.search(r"<tool_call>(.*?)</tool_call>", ass)
            if tc:
                obj = json.loads(tc.group(1))
                args = obj.get("args", obj)
                ok, _ = is_description_aligned(args.get("category", ""), args.get("description", ""))
                if not ok:
                    f.write(json.dumps(s, ensure_ascii=False) + "\n")
    print(f"Removed 樣本已存至: {rem_path}")

if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else "dataset/raw_generated.jsonl"
    dst = sys.argv[2] if len(sys.argv) > 2 else "dataset/raw_filtered.jsonl"
    filter_file(src, dst)
